export function t(key, ...args) {
  const v = RU[key];
  if (typeof v === 'function') return v(...args);
  return v ?? key;
}

export function tRandom(key) {
  const arr = RU[key];
  if (!Array.isArray(arr) || !arr.length) return '';
  return arr[Math.floor(Math.random() * arr.length)];
}
